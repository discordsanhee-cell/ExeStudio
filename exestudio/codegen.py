_b64_cache = {}


def _image_b64(path):
    if not path:
        return None
    p = Path(path)
    try:
        key = (str(p), p.stat().st_mtime)
    except OSError:
        return None
    if key not in _b64_cache:
        _b64_cache[key] = base64.b64encode(p.read_bytes()).decode("ascii")
    return _b64_cache[key]


def _items(s):
    return [x.strip() for x in str(s).split(",") if x.strip()]


def widget_lines(it):
    """Python statements creating one designer item as `self.<name>` inside `self.content`."""
    t, s = it["type"], f"self.{it['name']}"
    cls = TYPES[t]["cls"]
    L = []
    if t in ("label", "button", "checkbox", "radio"):
        L.append(f"{s} = {cls}({it.get('text', '')!r}, self.content)")
    elif t == "slider":
        L.append(f"{s} = QSlider(Qt.Orientation.Horizontal, self.content)")
    else:
        L.append(f"{s} = {cls}(self.content)")
    L.append(f"{s}.setGeometry({it['x']}, {it['y']}, {it['w']}, {it['h']})")
    if t == "label":
        L.append(f"{s}.setAlignment({ALIGN.get(it.get('align', 'left'), ALIGN['left'])})")
        L.append(f"{s}.setWordWrap(True)")
    elif t == "input":
        if it.get("placeholder"):
            L.append(f"{s}.setPlaceholderText({it['placeholder']!r})")
        if it.get("text"):
            L.append(f"{s}.setText({it['text']!r})")
        if it.get("password"):
            L.append(f"{s}.setEchoMode(QLineEdit.EchoMode.Password)")
    elif t == "textbox":
        if it.get("placeholder"):
            L.append(f"{s}.setPlaceholderText({it['placeholder']!r})")
        if it.get("text"):
            L.append(f"{s}.setPlainText({it['text']!r})")
    elif t in ("checkbox", "radio"):
        if it.get("checked"):
            L.append(f"{s}.setChecked(True)")
    elif t in ("combo", "list"):
        L.append(f"{s}.addItems({_items(it.get('items', ''))!r})")
    elif t in ("slider", "progress", "spin"):
        L.append(f"{s}.setRange({int(it.get('min', 0))}, {int(it.get('max', 100))})")
        L.append(f"{s}.setValue({int(it.get('value', 0))})")
    elif t == "image":
        data = _image_b64(it.get("path"))
        if data:
            L.append("_pix = QPixmap()")
            L.append(f"_pix.loadFromData(base64.b64decode({data!r}))")
            L.append(f"{s}.setPixmap(_pix)")
            L.append(f"{s}.setScaledContents(True)")
        else:
            L.append(f"{s}.setText('🖼 이미지')")
            L.append(f"{s}.setAlignment(Qt.AlignmentFlag.AlignCenter)")
    L.append(f"{s}.setStyleSheet({item_qss(it)!r})")
    if it.get("tooltip"):
        L.append(f"{s}.setToolTip({it['tooltip']!r})")
    return L


def _handler_lines(it):
    act, arg = it.get("action", "none"), it.get("action_arg", "")
    if act == "message":
        return [f"QMessageBox.information(self, {it.get('text', '알림')!r}, {arg!r})"]
    if act == "show_input":
        return [f"w = getattr(self, {arg!r}, None)",
                "txt = w.toPlainText() if hasattr(w, 'toPlainText') else (w.text() if w is not None else '')",
                "QMessageBox.information(self, '입력한 내용', txt or '(비어 있음)')"]
    if act == "url":
        return [f"QDesktopServices.openUrl(QUrl({arg!r}))"]
    if act == "run":
        return [f"subprocess.Popen({arg!r}, shell=True)"]
    if act == "close":
        return ["self.close()"]
    if act == "code" and arg.strip():
        return arg.replace("\t", "    ").splitlines()
    return ["# TODO: 여기에 버튼을 눌렀을 때 할 일을 작성하세요", "pass"]


def _window_lines(design, titlebar_cfg, actions=True):
    """Imports + TITLEBAR_CONFIG + `class MainWindow` for a designer layout (no __main__ block)."""
    cfg = merge_config(titlebar_cfg)
    cfg["title"] = design.get("title", cfg["title"])
    w, h = int(design.get("width", 720)), int(design.get("height", 480))
    content_qss = f"#FramelessContent {{ background: {qss_color(design.get('bg', '#14151c'))}; }}"
    out = ["",
           "# ============================== 앱 화면 ==============================",
           "import base64",
           "import subprocess",
           "",
           "from PySide6.QtCore import QUrl",
           "from PySide6.QtGui import QDesktopServices, QPixmap",
           "from PySide6.QtWidgets import (QCheckBox, QComboBox, QFrame, QLineEdit, QListWidget, QMessageBox,",
           "                               QProgressBar, QPushButton, QRadioButton, QSlider, QSpinBox, QTextEdit)",
           "",
           f"TITLEBAR_CONFIG = {pformat(cfg, width=110, sort_dicts=False)}",
           f"DESIGN_ITEMS = {[(it['name'], it['type']) for it in design.get('items', [])]!r}",
           "", "",
           "class MainWindow(FramelessWindow):",
           "    def __init__(self):",
           "        super().__init__(TITLEBAR_CONFIG)",
           f"        self.resize({w} + 2, {h} + TITLEBAR_CONFIG['height'] + 2)",
           f"        self.content.setStyleSheet({content_qss!r})",
           "        self.build_ui()",
           "",
           "    def build_ui(self):"]
    items = design.get("items", [])
    if not items:
        out.append("        pass")
    for it in items:
        out += ["        " + ln for ln in widget_lines(it)]
        if actions and it["type"] == "button":
            out.append(f"        self.{it['name']}.clicked.connect(self.on_{it['name']}_clicked)")
        out.append("")
    if actions:
        for it in items:
            if it["type"] == "button":
                out.append(f"    def on_{it['name']}_clicked(self):")
                out += ["        " + ln for ln in _handler_lines(it)]
                out.append("")
    return out


def design_to_code(design, titlebar_cfg):
    out = [HEADER, frameless_source()] + _window_lines(design, titlebar_cfg)
    out += ["",
            'if __name__ == "__main__":',
            "    app = QApplication(sys.argv)",
            "    win = MainWindow()",
            "    win.show()",
            "    sys.exit(app.exec())",
            ""]
    return chr(10).join(out)


