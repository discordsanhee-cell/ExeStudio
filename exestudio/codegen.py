def block_program(design, titlebar_cfg, logic, title):
    """Full program for block coding: designer window + event runtime + generated block logic."""
    has_design = bool(design.get("items"))
    if not has_design:
        design = dict(design, title=title, width=480, height=320)
    out = [HEADER.replace("Generated by EXE Studio", "EXE Studio 블록 코딩 + GUI 디자이너로 만든 프로그램"),
           frameless_source()]
    out += _window_lines(design, titlebar_cfg, actions=False)
    out += ["", block_runtime_source(), "",
            "# ============================== 블록 코드 ==============================",
            logic.strip(), "", "",
            'if __name__ == "__main__":',
            f"    _esd_main(MainWindow, {has_design}, {(design.get('title') or title)!r})",
            ""]
    return chr(10).join(out)


