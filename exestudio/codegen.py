        return (f"QComboBox{{{base} padding:0 10px;}} QComboBox::drop-down{{border:none; width:24px;}} "
                f"QComboBox QAbstractItemView{{background:{bg}; color:{fg}; selection-background-color:{acc}; "
                f"outline:0;}}")
