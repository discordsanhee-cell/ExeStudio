import os
import uuid
from pathlib import Path

from PySide6.QtWidgets import (QCheckBox, QFormLayout, QHBoxLayout, QLineEdit, QMessageBox, QPlainTextEdit,
                               QSplitter, QVBoxLayout, QWidget)
from PySide6.QtCore import Qt

from .. import toolchain
from ..widgets import LogConsole, Page, PathPicker, ProcessRunner, button, card, label, reveal
from .build import to_ico


class InstallerPage(Page):
    TITLE = "설치파일 만들기"
    SUBTITLE = "빌드한 EXE(또는 폴더)를 Inno Setup으로 'Setup.exe' 설치 프로그램으로 만듭니다. 바탕화면 바로가기, 시작 메뉴, 제거 기능 포함."

    def __init__(self, ctx):
        super().__init__(ctx)
        self.runner = ProcessRunner(self)
        self.guid = str(uuid.uuid4()).upper()
        split = QSplitter(Qt.Orientation.Horizontal)
        self.root.addWidget(split, 1)

        left = QWidget()
        ll = QVBoxLayout(left)
        ll.setContentsMargins(0, 0, 10, 0)
        c, cl = card()
        f = QFormLayout()
        f.setSpacing(8)
        self.app_name = QLineEdit("MyApp")
        self.version = QLineEdit("1.0.0")
        self.publisher = QLineEdit()
        self.url = QLineEdit()
        self.source = PathPicker("open", "EXE (*.exe)", "빌드된 메인 EXE 파일")
        self.whole_dir = QCheckBox("EXE가 있는 폴더 전체를 포함 (onedir 빌드)")
        self.icon = PathPicker("open", "아이콘 (*.ico *.png)", "설치 프로그램 아이콘 (선택)")
        self.out = PathPicker("dir", "", "Setup.exe를 저장할 폴더")
        self.license = PathPicker("open", "텍스트 (*.txt *.rtf)", "라이선스 파일 (선택)")
        self.desktop = QCheckBox("바탕화면 바로가기")
        self.desktop.setChecked(True)
        self.run_after = QCheckBox("설치 후 바로 실행")
        self.run_after.setChecked(True)
        self.admin = QCheckBox("모든 사용자용 설치 (관리자 권한)")
        self.big = QCheckBox("대용량 (2GB 넘는 프로그램, 디스크 분할)")
        for w, t in [(self.app_name, "앱 이름"), (self.version, "버전"), (self.publisher, "제작자"),
                     (self.url, "웹사이트"), (self.source, "메인 EXE"), (self.whole_dir, ""), (self.icon, "아이콘"),
                     (self.out, "출력 폴더"), (self.license, "라이선스"), (self.desktop, ""), (self.run_after, ""),
                     (self.admin, ""), (self.big, "")]:
            f.addRow(t, w)
        cl.addLayout(f)
        row = QHBoxLayout()
        row.addWidget(button("📝 스크립트 생성", self.generate))
        row.addWidget(button("💿 Setup.exe 만들기", self.compile, accent=True))
        row.addStretch(1)
        cl.addLayout(row)
        self.iscc_status = label("", "Sub", wrap=True)
        cl.addWidget(self.iscc_status)
        cl.addWidget(button("Inno Setup 설치 (winget)", self.install_inno))
        ll.addWidget(c)
        ll.addStretch(1)
        split.addWidget(left)

        right = QWidget()
        rl = QVBoxLayout(right)
        rl.setContentsMargins(10, 0, 0, 0)
        rl.addWidget(label("Inno Setup 스크립트 (.iss) — 직접 수정해도 돼요", "Sub"))
        self.script = QPlainTextEdit()
        self.script.setObjectName("Console")
        rl.addWidget(self.script, 2)
        self.log = LogConsole()
        rl.addWidget(self.log, 1)
        split.addWidget(right)
        split.setSizes([460, 640])
        self.runner.output.connect(self.log.append_text)
        self.runner.finished.connect(self._done)

    def on_show(self):
        iscc = toolchain.find_iscc()
        self.iscc_status.setText(f"✔ Inno Setup 찾음: {iscc}" if iscc else
                                 "⚠ Inno Setup이 없어요. 아래 버튼으로 설치하세요.")

    def set_source(self, exe, whole_dir, name, version, icon):
        self.source.setText(str(exe))
        self.whole_dir.setChecked(bool(whole_dir))
        if name:
            self.app_name.setText(name)
        if version:
            self.version.setText(version)
        if icon:
            self.icon.setText(icon)
        if not self.out.text():
            self.out.setText(str(Path(exe).parent if not whole_dir else Path(exe).parent.parent))

    def generate(self):
        exe = Path(self.source.text())
        if not exe.is_file():
            QMessageBox.warning(self, "EXE 없음", "메인 EXE 파일을 선택하세요.")
            return None
        name = self.app_name.text().strip() or exe.stem
        out = Path(self.out.text() or exe.parent)
        icon = self.icon.text()
        if icon and not icon.lower().endswith(".ico"):
            icon = to_ico(icon, str(out / "setup_icon.ico"))
        iscc = toolchain.find_iscc()
        korean = bool(iscc) and (Path(iscc).parent / "Languages" / "Korean.isl").exists()
        if self.whole_dir.isChecked():
            files = f'Source: "{exe.parent}\\*"; DestDir: "{{app}}"; Flags: ignoreversion recursesubdirs createallsubdirs'
        else:
            files = f'Source: "{exe}"; DestDir: "{{app}}"; Flags: ignoreversion'
        safe = "".join(ch for ch in name if ch.isalnum() or ch in "-_") or "App"
        lines = [
            "; Generated by EXE Studio",
            "[Setup]",
            f"AppId={{{{{self.guid}}}",
            f"AppName={name}",
            f"AppVersion={self.version.text()}",
            f"AppPublisher={self.publisher.text()}",
            f"AppPublisherURL={self.url.text()}" if self.url.text() else None,
            f"DefaultDirName={{autopf}}\\{name}",
            f"DefaultGroupName={name}",
            f"UninstallDisplayIcon={{app}}\\{exe.name}",
            f"OutputDir={out}",
            f"OutputBaseFilename={safe}_Setup_{self.version.text()}",
            f"SetupIconFile={icon}" if icon else None,
            f"LicenseFile={self.license.text()}" if self.license.text() else None,
            "Compression=lzma2/ultra64",
            "SolidCompression=yes",
            "WizardStyle=modern",
            "PrivilegesRequired=" + ("admin" if self.admin.isChecked() else "lowest"),
            "PrivilegesRequiredOverridesAllowed=dialog",
            "ArchitecturesInstallIn64BitMode=x64compatible",
            "DiskSpanning=yes" if self.big.isChecked() else None,
            "",
            "[Languages]",
            'Name: "korean"; MessagesFile: "compiler:Languages\\Korean.isl"' if korean else None,
            'Name: "english"; MessagesFile: "compiler:Default.isl"',
            "",
            "[Tasks]",
            'Name: "desktopicon"; Description: "{cm:CreateDesktopIcon}"; GroupDescription: "{cm:AdditionalIcons}"'
            + ("" if self.desktop.isChecked() else "; Flags: unchecked"),
            "",
            "[Files]",
            files,
            "",
            "[Icons]",
            f'Name: "{{group}}\\{name}"; Filename: "{{app}}\\{exe.name}"',
            f'Name: "{{group}}\\{{cm:UninstallProgram,{name}}}"; Filename: "{{uninstallexe}}"',
            f'Name: "{{autodesktop}}\\{name}"; Filename: "{{app}}\\{exe.name}"; Tasks: desktopicon',
            "",
        ]
        if self.run_after.isChecked():
            lines += ["[Run]",
                      f'Filename: "{{app}}\\{exe.name}"; Description: "{{cm:LaunchProgram,{name}}}"; '
                      "Flags: nowait postinstall skipifsilent"]
        text = "\n".join(ln for ln in lines if ln is not None) + "\n"
        self.script.setPlainText(text)
        return out

    def compile(self):
        iscc = toolchain.find_iscc()
        if not iscc:
            QMessageBox.information(self, "Inno Setup 필요", "Inno Setup을 먼저 설치하세요. (버튼 한 번이면 돼요)")
            return
        out = self.generate() if not self.script.toPlainText().strip() else Path(self.out.text() or ".")
        if out is None:
            return
        out.mkdir(parents=True, exist_ok=True)
        iss = out / f"{self.app_name.text().strip() or 'setup'}.iss"
        iss.write_text(self.script.toPlainText(), encoding="utf-8-sig")
        self._out = out
        self.runner.run([[iscc, str(iss)]], cwd=str(out))

    def _done(self, code):
        if code == 0 and getattr(self, "_out", None):
            self.toast("Setup.exe 완성 🎉")
            reveal(self._out)
        self.on_show()

    def install_inno(self):
        self.runner.run([toolchain.winget_install_args("JRSoftware.InnoSetup")])
